// Package templates 提供内置的多阶段 Dockerfile，当仓库未自带
// Dockerfile 时作为回退方案使用。
//
// 选择依据是仓库根目录下的语言标记文件（见 Detect）。仓库自带的 Dockerfile
// 始终优先于这些模板；仅当仓库没有 Dockerfile 时，构建器才会查阅本包。
package templates

import (
	"embed"
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
)

//go:embed go.Dockerfile node.Dockerfile vue.Dockerfile java.Dockerfile gradle.Dockerfile rust.Dockerfile scripts/*.sh entrypoints/*.sh
var files embed.FS

// Name 标识一个内置模板。
type Name string

const (
	NameGo     Name = "go"
	NameNode   Name = "node"
	NameVue    Name = "vue"
	NameJava   Name = "java"
	NameGradle Name = "gradle"
	NameRust   Name = "rust"
)

// Template 是一个检测到的内置构建配方。
type Template struct {
	Name    Name
	Content []byte
}

// ScriptPath 是构建器写入模板所调用构建脚本的固定位置（相对于仓库根目录）。
const ScriptPath = ".code-builder/build.sh"

// EntrypointPath 是构建器写入模板运行入口的固定位置。
const EntrypointPath = ".code-builder/entrypoint.sh"

// scriptByTemplate 将模板映射到其运行的嵌入式构建脚本。
var scriptByTemplate = map[Name]string{
	NameGo:     "scripts/build-go.sh",
	NameJava:   "scripts/build-maven.sh",
	NameGradle: "scripts/build-gradle.sh",
	NameNode:   "scripts/build-node.sh",
	NameVue:    "scripts/build-node.sh",
	NameRust:   "scripts/build-rust.sh",
}

var entrypointByTemplate = map[Name]string{
	NameGo:     "entrypoints/app.sh",
	NameRust:   "entrypoints/app.sh",
	NameJava:   "entrypoints/java.sh",
	NameGradle: "entrypoints/java.sh",
	NameNode:   "entrypoints/node.sh",
}

// Entrypoint 返回模板运行镜像使用的入口脚本。Vue 静态模板没有入口脚本。
func Entrypoint(name Name) (content []byte, ok bool) {
	path, ok := entrypointByTemplate[name]
	if !ok {
		return nil, false
	}
	content, err := files.ReadFile(path)
	if err != nil {
		return nil, false
	}
	return content, true
}

// Script 返回指定模板所调用的构建脚本。
func Script(name Name) (content []byte, ok bool) {
	path, ok := scriptByTemplate[name]
	if !ok {
		return nil, false
	}
	content, err := files.ReadFile(path)
	if err != nil {
		return nil, false
	}
	return content, true
}

// Detect 检查 repoDir 中的语言标记文件并返回匹配的内置模板。
func Detect(repoDir string) (Template, bool) {
	name, ok := detectName(repoDir)
	if !ok {
		return Template{}, false
	}
	content, err := files.ReadFile(string(name) + ".Dockerfile")
	if err != nil {
		return Template{}, false
	}
	return Template{Name: name, Content: content}, true
}

func detectName(repoDir string) (Name, bool) {
	switch {
	case isFile(filepath.Join(repoDir, "go.mod")):
		return NameGo, true
	case isFile(filepath.Join(repoDir, "Cargo.toml")):
		return NameRust, true
	case isFile(filepath.Join(repoDir, "pom.xml")):
		return NameJava, true
	case isFile(filepath.Join(repoDir, "build.gradle")) || isFile(filepath.Join(repoDir, "build.gradle.kts")):
		return NameGradle, true
	case isFile(filepath.Join(repoDir, "package.json")):
		if packageIsFrontend(repoDir) {
			return NameVue, true
		}
		return NameNode, true
	}
	return "", false
}

func isFile(path string) bool {
	st, err := os.Stat(path)
	return err == nil && !st.IsDir()
}

// packageIsFrontend 报告 package.json 是否声明了常见前端框架 / 构建工具。
// 命中后使用 nginx 托管 dist/ 产物。
func packageIsFrontend(repoDir string) bool {
	data, err := os.ReadFile(filepath.Join(repoDir, "package.json"))
	if err != nil {
		return false
	}
	var pkg struct {
		Dependencies    map[string]json.RawMessage `json:"dependencies"`
		DevDependencies map[string]json.RawMessage `json:"devDependencies"`
		Scripts         map[string]string          `json:"scripts"`
	}
	if err := json.Unmarshal(data, &pkg); err != nil {
		return false
	}
	// 没有 build 脚本时不套静态前端模板，避免构建后没有 dist/。
	if pkg.Scripts["build"] == "" {
		return false
	}
	for _, deps := range []map[string]json.RawMessage{pkg.Dependencies, pkg.DevDependencies} {
		for dep := range deps {
			switch {
			case dep == "vue", dep == "react", dep == "react-dom",
				dep == "svelte", dep == "astro", dep == "solid-js", dep == "vite",
				strings.HasPrefix(dep, "@vue/"),
				strings.HasPrefix(dep, "vue-"),
				strings.HasPrefix(dep, "@angular/"),
				strings.HasPrefix(dep, "@sveltejs/"):
				return true
			}
		}
	}
	return false
}

// DefaultDockerignore 在使用内置模板且仓库没有 .dockerignore 时写入。
// 注意绝不能排除 .code-builder，否则模板调用的构建脚本不会进入构建上下文。
const DefaultDockerignore = `# generated by code-builder (only when the repository has no .dockerignore)
.git
node_modules
target
coverage
*.log
.DS_Store
`

// EnsureDockerignore 在仓库根目录没有 .dockerignore 时写入默认内容。
func EnsureDockerignore(repoDir string) (bool, error) {
	path := filepath.Join(repoDir, ".dockerignore")
	if _, err := os.Stat(path); err == nil {
		return false, nil
	}
	if err := os.WriteFile(path, []byte(DefaultDockerignore), 0o644); err != nil {
		return false, err
	}
	return true, nil
}

// DockerignoreExcludesBuildDir 报告仓库已有的 .dockerignore 是否排除了
// 构建器写入的 .code-builder 目录。排除会导致模板的 RUN 找不到脚本。
func DockerignoreExcludesBuildDir(repoDir string) bool {
	data, err := os.ReadFile(filepath.Join(repoDir, ".dockerignore"))
	if err != nil {
		return false
	}
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") || strings.HasPrefix(line, "!") {
			continue
		}
		line = strings.TrimPrefix(line, "/")
		line = strings.TrimSuffix(line, "/")
		if line == ".code-builder" || line == ".code-builder*" || line == ".*" || line == "**/.*" ||
			strings.HasPrefix(line, ".code-builder/") || strings.HasPrefix(line, "**/.code-builder") {
			return true
		}
	}
	return false
}
